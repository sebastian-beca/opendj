//! rbox reads some `master.db` columns as never empty, and one NULL in any
//! of them fails the whole import ("Unexpected null for non-null column").
//! Libraries that went through older rekordbox versions, migrations or
//! other tools can hold NULLs there. They are filled with an empty value in
//! the private copy that [`super::dates`] makes; the DJ's own `master.db` is
//! never written.
//!
//! [`REQUIRED`] lists every column rbox-masterdb 0.3.0's `schema.rs` declares
//! without `Nullable`, leaving out primary keys and the dates that
//! [`super::dates`] already fixes. Regenerate it when rbox is updated.

use rusqlite::Connection;

/// What a NULL becomes.
#[derive(Clone, Copy)]
pub enum Fill {
    /// `''`
    Text,
    /// `0`
    Zero,
}

impl Fill {
    fn sql(self) -> &'static str {
        match self {
            Fill::Text => "''",
            Fill::Zero => "0",
        }
    }
}

