/// The required columns this library has, as `(table, column, fill)`.
fn present(c: &Connection) -> rusqlite::Result<Vec<(&'static str, &'static str, Fill)>> {
    let mut out = Vec::new();
    let mut cols = c.prepare("SELECT 1 FROM pragma_table_info(?1) WHERE name = ?2")?;
    for &(t, col, fill) in REQUIRED {
        if cols.exists([t, col])? {
            out.push((t, col, fill));
        }
    }
    Ok(out)
}

/// Whether any required column holds a NULL.
pub fn any(c: &Connection) -> rusqlite::Result<bool> {
    for (t, col, _) in present(c)? {
        let mut q = c.prepare(&format!(
            "SELECT 1 FROM \"{t}\" WHERE \"{col}\" IS NULL LIMIT 1"
        ))?;
        if q.exists([])? {
            return Ok(true);
        }
    }
    Ok(false)
}

/// Fills every NULL in a required column. Returns how many it changed.
pub fn fill(c: &Connection) -> rusqlite::Result<usize> {
    let mut changed = 0;
    for (t, col, fill) in present(c)? {
        changed += c.execute(
            &format!(
                "UPDATE \"{t}\" SET \"{col}\" = {} WHERE \"{col}\" IS NULL",
                fill.sql()
            ),
            [],
        )?;
    }
    Ok(changed)
}
